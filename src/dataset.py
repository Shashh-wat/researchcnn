"""Modality-agnostic (real, K synthetic draws, label) dataset (architecture.md §2, last row).

Expected layout, works identically for lung-CT or dental-radiograph domains:

    real_manifest.csv      columns: path,label      label=1 -> real_used, label=0 -> real_not_used
    synth_dir/              flat pool of synthetic images generated by the GAN/diffusion model

Usage:
    ds = RealSyntheticSetDataset("real_manifest.csv", "synth_dir/", k=8)
"""
import csv
import random
from pathlib import Path

import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]


def _ensure_rgb(im: Image.Image) -> Image.Image:
    # module-level (not a lambda/closure) so it survives pickling to DataLoader worker
    # processes under the "spawn" start method (default on macOS/Windows).
    return im.convert("RGB")


def default_transform(image_size: int = 224) -> transforms.Compose:
    return transforms.Compose(
        [
            transforms.Resize((image_size, image_size)),
            transforms.Lambda(_ensure_rgb),
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ]
    )


class RealSyntheticSetDataset(Dataset):
    def __init__(self, real_manifest_csv: str, synth_dir: str, k: int = 8,
                 transform: transforms.Compose = None, image_size: int = 224):
        self.k = k
        self.transform = transform or default_transform(image_size)

        with open(real_manifest_csv, newline="") as f:
            reader = csv.DictReader(f)
            self.real_items = [(row["path"], int(row["label"])) for row in reader]

        synth_dir = Path(synth_dir)
        exts = {".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"}
        self.synth_pool = sorted(str(p) for p in synth_dir.iterdir() if p.suffix.lower() in exts)
        if len(self.synth_pool) == 0:
            raise ValueError(f"No synthetic images found in {synth_dir}")

    def __len__(self) -> int:
        return len(self.real_items)

    def _load(self, path: str) -> torch.Tensor:
        img = Image.open(path)
        return self.transform(img)

    def __getitem__(self, idx: int):
        real_path, label = self.real_items[idx]
        real_tensor = self._load(real_path)

        replace = len(self.synth_pool) < self.k
        draw_paths = random.choices(self.synth_pool, k=self.k) if replace else random.sample(self.synth_pool, self.k)
        synth_tensor = torch.stack([self._load(p) for p in draw_paths], dim=0)  # (K,3,H,W)

        return real_tensor, synth_tensor, torch.tensor(label, dtype=torch.long)
